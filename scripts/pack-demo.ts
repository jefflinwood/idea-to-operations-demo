// Embeds demo-app/ into src/demo-files.generated.ts so the Worker can seed the base Artifacts repo.
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
const root = new URL("../demo-app/", import.meta.url).pathname;
const files: Record<string, string> = {};
const walk = (dir: string) => { for (const f of readdirSync(dir).sort()) { const p = join(dir, f); if (f === "node_modules") continue; statSync(p).isDirectory() ? walk(p) : (files[relative(root, p)] = readFileSync(p, "utf8")); } };
walk(root);
writeFileSync(new URL("../src/demo-files.generated.ts", import.meta.url), `// Generated by scripts/pack-demo.ts. Do not edit.\nexport const DEMO_FILES: Record<string, string> = ${JSON.stringify(files, null, 1)};\n`);
console.log(`packed ${Object.keys(files).length} files`);
